#!/usr/bin/env node
/**
 * Fills the subtopics' Overview (entry_chapters.overview) of the topics
 * imported from the old site. The first import (import-topics.mjs) put each
 * overview, cut to 300 characters, in the subtopic's key points; this reads
 * the whole overview, paragraph by paragraph, from the old pages.
 *
 *   node scripts/webflow/import-overviews.mjs --sql supabase/migrations/<version>_<name>.sql
 *        [--data scripts/webflow/data/global-issues.json] [--origin https://atlasoftodaysworld.webflow.io]
 *
 * Writes a data migration (one UPDATE; the deploy runs it on production). It
 * only fills an empty overview of the subtopic at the same position with the
 * same title, and drops the key point only while it is still the cut copy of
 * the overview — what editors wrote or changed stays. Repeatable.
 * Runs headless Chromium from the dev dependency Playwright.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { parseArgs } from "node:util";
import { chromium } from "@playwright/test";

const { values: args } = parseArgs({
  options: {
    data: { type: "string", default: "scripts/webflow/data/global-issues.json" },
    // www.atlasoftodaysworld.org serves the new site now.
    origin: { type: "string", default: "https://atlasoftodaysworld.webflow.io" },
    sql: { type: "string" },
  },
});
if (!args.sql) throw new Error("Usage: --sql <file>");

const { topics } = JSON.parse(readFileSync(args.data, "utf8"));

/** Runs in the page: each chapter tab's Overview box — its title and paragraphs. */
function readOverviews() {
  const text = (el) => (el ? el.textContent.replace(/\s+/g, " ").trim() : "");
  return [...document.querySelectorAll(".complete-picture-body")].map((box) => {
    const body = box.querySelector(".rich-text-big-picture");
    const paragraphs = body ? [...body.querySelectorAll("p")].map(text).filter(Boolean) : [];
    return {
      title: text(box.querySelector(".complete-picture-title")),
      overview: paragraphs.length ? paragraphs.join("\n\n") : text(body),
    };
  });
}

const browser = await chromium.launch();
const page = await browser.newPage();
const rows = [];
for (const topic of topics) {
  await page.goto(`${args.origin}${topic.oldPath}`, { waitUntil: "domcontentloaded" });
  const boxes = await page.evaluate(readOverviews);
  topic.chapters.slice(0, 12).forEach((chapter, position) => {
    const box = boxes.find((item) => item.title === chapter.title) ?? boxes[position];
    const overview = (box?.overview ?? "").slice(0, 3000);
    if (!overview) console.warn(`${topic.slug} #${position + 1}: no overview on the old page`);
    else
      rows.push({
        slug: topic.slug,
        position,
        title: chapter.title.trim().slice(0, 200),
        overview,
      });
  });
  console.log(`${topic.slug}: ${boxes.length} overview boxes`);
}
await browser.close();

const payload = JSON.stringify(rows);
if (payload.includes("$ov$")) throw new Error("A text contains the quote tag $ov$.");
// The cut key point is the overview's start without its paragraph breaks.
const squash = (column) => `regexp_replace(${column}, '\\s', '', 'g')`;
writeFileSync(
  args.sql,
  `-- The subtopics' Overview from the old site (generated by
-- scripts/webflow/import-overviews.mjs from ${args.origin}).
-- Fills only empty overviews of subtopics still at the same position with the
-- same title; drops the key point only while it is the cut copy of the
-- overview the first import made. Repeatable; nothing else changes.

with data as (
  select * from jsonb_to_recordset($ov$${payload}$ov$::jsonb)
    as d(slug text, position int, title text, overview text)
)
update entry_chapters c
     set overview = d.overview,
         summary_points = case when cardinality(c.summary_points) = 1
                                and starts_with(${squash("d.overview")}, ${squash("c.summary_points[1]")})
                               then '{}'::text[] else c.summary_points end
    from data d
    join entries e on e.slug = d.slug and e.locale = 'en'
   where c.entry_id = e.id and c.position = d.position and c.title = d.title and c.overview = '';
`,
);
console.log(`\n${rows.length} overviews in ${topics.length} topics → ${args.sql}`);
